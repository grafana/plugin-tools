import { describe, expect, it } from 'vitest';
import { Context } from '../../context.js';
import migrate from './022-config-docs.js';

const README_PATH = '.config/README.md';
const oldReadme = '### Extending the ESLint config\n\nEdit `.eslintrc`.\n';

describe('022-config-docs', () => {
  it('replaces the generated README with a warning and a link to the configuration guide', () => {
    const context = new Context('/virtual');
    context.addFile(README_PATH, oldReadme);

    const readme = migrate(context).getFile(README_PATH);

    expect(readme).toContain('DO NOT EDIT THIS FILE DIRECTLY.');
    expect(readme).toContain('https://grafana.com/developers/plugin-tools/how-to-guides/extend-configurations');
    expect(readme).not.toContain(oldReadme);
  });

  it('keeps the README after Prettier reformats the warning', () => {
    const formattedReadme = [
      '/*',
      '',
      '- DO NOT EDIT THIS FILE DIRECTLY.',
      '*/',
      '',
      '[Extend default configurations guide](https://grafana.com/developers/plugin-tools/how-to-guides/extend-configurations)',
      '',
    ].join('\n');
    const context = new Context('/virtual');
    context.addFile(README_PATH, formattedReadme);

    expect(migrate(context).getFile(README_PATH)).toBe(formattedReadme);
  });

  it('is idempotent', async () => {
    const context = new Context('/virtual');
    context.addFile(README_PATH, oldReadme);

    await expect(migrate).toBeIdempotent(context);
  });
});
