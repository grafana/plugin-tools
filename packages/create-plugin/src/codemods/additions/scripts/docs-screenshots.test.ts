import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Context } from '../../context.js';
import docsScreenshots from './docs-screenshots.js';

const panel = { type: 'panel', name: 'Clock', id: 'grafana-clock-panel', docsPath: 'catalog-docs' };
const e2ePackageJson = {
  scripts: { 'docs:validate': 'plugin-docs-cli validate' },
  devDependencies: { '@grafana/plugin-e2e': '^4.0.0', '@playwright/test': '^1.62.1' },
};
const docsFiles = {
  'catalog-docs/index.md': '# Clock\n\n<!-- screenshot: the clock panel -->\n',
  'catalog-docs/AGENTS.md': '# Agents\n',
  'playwright.config.ts': 'export default {};\n',
  '.config/AGENTS/instructions.md': '# Grafana Plugin\n',
};

function makeContext(
  pluginJson: Record<string, unknown> = panel,
  files: Record<string, string> = docsFiles,
  packageJson: Record<string, unknown> = e2ePackageJson
): Context {
  const context = new Context('/virtual');
  context.addFile('src/plugin.json', JSON.stringify(pluginJson));
  context.addFile('package.json', JSON.stringify(packageJson));
  for (const [path, content] of Object.entries(files)) {
    context.addFile(path, content);
  }
  return context;
}

function grafanaHealth(): Response {
  return new Response(JSON.stringify({ database: 'ok', version: '12.0.0' }), { status: 200 });
}

const fetchMock = vi.fn(async (_url: string) => grafanaHealth());

describe('docs-screenshots', () => {
  const originalGrafanaUrl = process.env.GRAFANA_URL;

  beforeEach(() => {
    delete process.env.GRAFANA_URL;
    fetchMock.mockReset();
    fetchMock.mockImplementation(async () => grafanaHealth());
    vi.stubGlobal('fetch', fetchMock);
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    if (originalGrafanaUrl === undefined) {
      delete process.env.GRAFANA_URL;
    } else {
      process.env.GRAFANA_URL = originalGrafanaUrl;
    }
  });

  it('should scaffold the screenshot project', async () => {
    const result = await docsScreenshots(makeContext());

    expect(result.getFile('docs-screenshots/playwright.config.ts')).toContain("from '../playwright.config'");
    expect(result.getFile('.config/docs-screenshots/helpers.ts')).toContain('captureDocsScreenshot');
    expect(result.getFile('docs-screenshots/example.spec.ts')).toContain('gotoDashboardPage');
  });

  it.each([
    ['datasource', 'createDataSourceConfigPage'],
    ['app', 'gotoAppPage'],
  ])('should add the %s example spec', async (type, fixture) => {
    const result = await docsScreenshots(makeContext({ ...panel, type }));
    const example = result.getFile('docs-screenshots/example.spec.ts');

    expect(example).toContain(fixture);
    expect(example).toContain("'grafana-clock-panel'");
  });

  it('should add the docs:screenshots script and keep the other scripts', async () => {
    const result = await docsScreenshots(makeContext());
    const { scripts } = JSON.parse(result.getFile('package.json') ?? '{}');

    expect(scripts).toEqual({
      'docs:validate': 'plugin-docs-cli validate',
      'docs:screenshots':
        'playwright install chromium && playwright test --config docs-screenshots/playwright.config.ts && plugin-docs-cli validate',
    });
  });

  it('should keep a docs:screenshots script the author changed', async () => {
    const packageJson = { ...e2ePackageJson, scripts: { 'docs:screenshots': 'custom' } };
    const result = await docsScreenshots(makeContext(panel, docsFiles, packageJson));

    expect(JSON.parse(result.getFile('package.json') ?? '{}').scripts['docs:screenshots']).toBe('custom');
  });

  it('should add a docs screenshots section to the agent instructions', async () => {
    const result = await docsScreenshots(makeContext());
    const instructions = result.getFile('.config/AGENTS/instructions.md');

    expect(instructions).toContain('## Docs screenshots');
    expect(instructions).toContain('`catalog-docs/img/`');
    expect(instructions).toContain('`docs:screenshots`');
  });

  it('should keep files the author already has', async () => {
    const result = await docsScreenshots(
      makeContext(panel, { ...docsFiles, 'docs-screenshots/options.spec.ts': '// mine\n' })
    );

    expect(result.getFile('docs-screenshots/options.spec.ts')).toBe('// mine\n');
    expect(result.doesFileExist('docs-screenshots/example.spec.ts')).toBe(false);
    expect(result.doesFileExist('docs-screenshots/playwright.config.ts')).toBe(true);
  });

  it('should read the docs folder from plugin.json instead of baking it into the helpers', async () => {
    const helpers = (await docsScreenshots(makeContext())).getFile('.config/docs-screenshots/helpers.ts');

    expect(helpers).toContain('DO NOT EDIT THIS FILE DIRECTLY');
    expect(helpers).toContain("'plugin.json'");
    expect(helpers).not.toContain('catalog-docs');
  });

  it('should bring outdated helpers up to date', async () => {
    const fresh = (await docsScreenshots(makeContext())).getFile('.config/docs-screenshots/helpers.ts');
    const result = await docsScreenshots(
      makeContext(panel, { ...docsFiles, '.config/docs-screenshots/helpers.ts': '// old\n' })
    );

    expect(result.getFile('.config/docs-screenshots/helpers.ts')).toBe(fresh);
  });

  it('should say where it found Grafana and how to take the screenshots again', async () => {
    const result = await docsScreenshots(makeContext());

    expect(result.getMessage()?.body?.join('\n')).toMatch(/http:\/\/localhost:3000.*docs:screenshots.*GRAFANA_URL/s);
  });

  it('should check Grafana and the plugin at localhost:3000 by default', async () => {
    await docsScreenshots(makeContext());

    expect(fetchMock.mock.calls.map(([url]) => url)).toEqual([
      'http://localhost:3000/api/health',
      'http://localhost:3000/api/plugins/grafana-clock-panel/settings',
    ]);
  });

  it('should use --grafanaUrl and pass it on to the agent and Playwright', async () => {
    await docsScreenshots(makeContext(), { grafanaUrl: 'http://localhost:3001/' });

    expect(fetchMock.mock.calls[0][0]).toBe('http://localhost:3001/api/health');
    expect(process.env.GRAFANA_URL).toBe('http://localhost:3001');
  });

  it('should use GRAFANA_URL when no --grafanaUrl is given', async () => {
    process.env.GRAFANA_URL = 'http://grafana.local:3000';
    await docsScreenshots(makeContext());

    expect(fetchMock.mock.calls[0][0]).toBe('http://grafana.local:3000/api/health');
  });

  it('should stop without changing files when Grafana is not running', async () => {
    fetchMock.mockRejectedValue(new TypeError('fetch failed'));
    const context = makeContext();

    await expect(docsScreenshots(context)).rejects.toThrow(
      /found no Grafana at http:\/\/localhost:3000.*--grafanaUrl/s
    );
    expect(context.doesFileExist('docs-screenshots/playwright.config.ts')).toBe(false);
  });

  it('should stop when something other than Grafana answers', async () => {
    fetchMock.mockResolvedValue(new Response('<html></html>', { status: 200 }));

    await expect(docsScreenshots(makeContext())).rejects.toThrow(/found no Grafana/);
  });

  it('should stop when Grafana has not loaded the plugin', async () => {
    fetchMock.mockImplementation(async (url: string) =>
      url.endsWith('/settings') ? new Response('{}', { status: 404 }) : grafanaHealth()
    );

    await expect(docsScreenshots(makeContext())).rejects.toThrow(/hasn't loaded the grafana-clock-panel plugin/);
  });

  it('should go on when Grafana needs a login to check the plugin', async () => {
    fetchMock.mockImplementation(async (url: string) =>
      url.endsWith('/settings') ? new Response('{}', { status: 401 }) : grafanaHealth()
    );

    await expect(docsScreenshots(makeContext())).resolves.toBeDefined();
  });

  it('should be idempotent', async () => {
    await expect(docsScreenshots).toBeIdempotent(makeContext());
  });

  it('should stop when the docs are not set up', async () => {
    const context = makeContext({ type: 'panel', name: 'Clock', id: 'grafana-clock-panel' });

    await expect(docsScreenshots(context)).rejects.toThrow(/no docsPath.*create-plugin add docs$/s);
  });

  it('should name docs-screenshots when the plugin type is not supported', async () => {
    const context = makeContext({ ...panel, type: 'renderer' });

    await expect(docsScreenshots(context)).rejects.toThrow(
      'create-plugin add docs-screenshots needs a plugin type of panel'
    );
  });

  it('should add plugin-e2e and Playwright when the plugin has neither', async () => {
    const result = await docsScreenshots(makeContext(panel, docsFiles, { scripts: {} }));
    const { devDependencies } = JSON.parse(result.getFile('package.json') ?? '{}');

    expect(devDependencies).toEqual({ '@grafana/plugin-e2e': '^4.0.0', '@playwright/test': '^1.62.1' });
  });

  it('should keep the versions a plugin already has', async () => {
    const devDependencies = { '@grafana/plugin-e2e': '^3.1.0', '@playwright/test': '^1.55.0' };
    const result = await docsScreenshots(makeContext(panel, docsFiles, { devDependencies }));

    expect(JSON.parse(result.getFile('package.json') ?? '{}').devDependencies).toEqual(devDependencies);
  });

  it('should raise a plugin-e2e that is too old for the theme option', async () => {
    const devDependencies = { '@grafana/plugin-e2e': '^1.8.0', '@playwright/test': '^1.55.0' };
    const result = await docsScreenshots(makeContext(panel, docsFiles, { devDependencies }));

    expect(JSON.parse(result.getFile('package.json') ?? '{}').devDependencies).toEqual({
      '@grafana/plugin-e2e': '^2.2.0',
      '@playwright/test': '^1.55.0',
    });
  });

  it('should extend the plugin Playwright config when there is one', async () => {
    const result = await docsScreenshots(makeContext());

    expect(result.getFile('docs-screenshots/playwright.config.ts')).toContain("from '../playwright.config'");
  });

  it('should write a standalone Playwright config when the plugin has none', async () => {
    const { 'playwright.config.ts': _config, ...files } = docsFiles;
    const result = await docsScreenshots(makeContext(panel, files, { scripts: {} }));
    const config = result.getFile('docs-screenshots/playwright.config.ts');

    expect(config).not.toContain("from '../playwright.config'");
    expect(config).toContain("name: 'auth'");
    expect(config).toContain('process.env.GRAFANA_URL');
    expect(result.doesFileExist('playwright.config.ts')).toBe(false);
  });

  it('should ignore the Playwright output and stored login in git', async () => {
    const result = await docsScreenshots(
      makeContext(panel, { ...docsFiles, '.gitignore': 'node_modules/\ntest-results/\n' })
    );

    expect(result.getFile('.gitignore')).toBe(
      'node_modules/\ntest-results/\n\n# docs screenshots\n/playwright/.auth/\n'
    );
  });

  it('should leave a gitignore that already has the entries alone', async () => {
    const gitignore = 'node_modules/\n/test-results/\n/playwright/.auth/\n';
    const result = await docsScreenshots(makeContext(panel, { ...docsFiles, '.gitignore': gitignore }));

    expect(result.getFile('.gitignore')).toBe(gitignore);
  });
});
